function upsert(filePath, localeMap) {
  const json = JSON.parse(fs.readFileSync(filePath, 'utf8'));
  if (!json.common || typeof json.common !== 'object') {
    throw new Error(`missing common namespace in ${filePath}`);
  }
  Object.assign(json.common, localeMap);
  fs.writeFileSync(filePath, `${JSON.stringify(json, null, 2)}\n`, 'utf8');
}

